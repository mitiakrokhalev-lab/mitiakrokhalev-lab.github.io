// ЯЗЫК ИНТЕРФЕЙСА.
//
// Задача непривычная: русский текст в этом проекте не «ресурсы», а часть
// кода — сообщения об ошибках, подписи, пояснения. Их около восьмисот только
// в бесплатной части, и треть с подстановками. Поэтому способ выбран такой,
// чтобы ПРАВКА КАЖДОЙ СТРОКИ БЫЛА В ОДИН СИМВОЛ, а код остался читаемым.
//
// Ключ — САМ РУССКИЙ ТЕКСТ, а не выдуманное имя вроде `applet.notLoaded`.
// Имена пришлось бы придумывать восемьсот раз, и читать потом не текст, а
// шифр: по строке `t('gen.budget.exceeded')` не видно, что человек увидит.
// Русский ключ хуже ровно одним — при правке текста надо поправить и словарь;
// но это ловит сторож (см. test/lang.test.js), а нечитаемый код не ловит никто.
//
// ПОДСТАНОВКИ — ЧЕРЕЗ ТЕГ-ШАБЛОН. Обычный вызов для таких строк потребовал бы
// переписать их в `t('было %1 из %2', a, b)`, то есть тронуть каждую. Тег
// позволяет приписать одну букву перед кавычкой:
//
//     say(`величин ${n} из ${all}`)     ->     say(t`величин ${n} из ${all}`)
//
// Ключом тогда служат неизменные куски, склеенные через разделитель, а в
// переводе места подстановки помечены НОМЕРАМИ — {1}, {2}. Номера нужны
// потому, что порядок слов в двух языках разный: значение, стоявшее первым,
// в английском нередко уезжает в конец, и без номеров перевод пришлось бы
// ломать под русский порядок.

// Разделитель — управляющий символ, которого в живом тексте быть не может.
// Записан ESCAPE-ПОСЛЕДОВАТЕЛЬНОСТЬЮ нарочно: настоящий символ в исходнике
// невидим, и однажды его вырежет редактор, линтер или чужая вставка — а
// заметить это будет нечем, ключи просто перестанут совпадать.
const SLOT = '\u0001';

// null значит «русский»: подменять нечего, строки и так на нём. Так русский
// не стоит ни байта и не может сломаться от дырки в словаре.
let dict = null;
let current = 'ru';

export const lang = () => current;

// Перевод. Два вызова в одном: обычной строкой и тегом-шаблоном.
export function t(x, ...vals) {
  if (!Array.isArray(x)) return dict?.[x] ?? x;
  const line = dict?.[x.join(SLOT)];

  // Перевода нет (или язык русский) — склеиваем исходное, как сделал бы сам
  // шаблон. Куски и значения чередуются, значений ровно на одно меньше.
  if (line === undefined) {
    let out = x[0];
    for (let i = 1; i < x.length; i++) out += String(vals[i - 1] ?? '') + x[i];
    return out;
  }

  // А ПЕРЕВОД ХРАНИТ МЕСТА ПОДСТАНОВКИ НОМЕРАМИ: {1}, {2}, …
  //
  // Номера, а не порядок следования, потому что порядок слов в двух языках
  // разный, и значение, стоявшее в русском первым, в английском нередко
  // уезжает в конец. «Величин 7 из 20» → «20 quantities, 7 of them kept»:
  // без номеров такой перевод записать нечем, и переводчику пришлось бы
  // ломать английскую фразу под русский порядок.
  //
  // Номер, которому нет значения, даёт пустоту — молча. Это лучше, чем
  // «undefined» посреди фразы; а что такой номер вообще появился, ловит
  // сторож в test/lang.test.js, и чинить это надо там, а не здесь.
  return line.replace(/\{(\d+)\}/g, (_, n) => String(vals[n - 1] ?? ''));
}

// ---- выбор языка -----------------------------------------------------------

const KEY = 'kropolyator:lang';

// Русский остаётся умолчанием ДАЖЕ ДЛЯ ЧУЖОГО БРАУЗЕРА, пока словарь не полон.
// Иначе англичанин увидит половину интерфейса на английском, половину на
// русском — и решит, что приложение сломано, а не что перевод не дописан.
// Когда словарь закроет всё, здесь появится определение по navigator.language.
export function savedLang() {
  try { return localStorage.getItem(KEY) || 'ru'; } catch { return 'ru'; }
}

// Словарь приезжает ОТДЕЛЬНЫМ модулем и только когда нужен: русскому
// посетителю незачем качать английские строки.
export async function setLang(code) {
  if (code === current) return;
  if (code === 'ru') { dict = null; current = 'ru'; }
  else {
    const mod = await import(`./${code}.js`);
    dict = mod.WORDS;
    current = code;
  }
  try { localStorage.setItem(KEY, current); } catch { /* приватный режим */ }
  for (const fn of listeners) { try { fn(current); } catch { /* не наше дело */ } }
}

// Кто хочет перерисоваться при смене языка. Разметка переводится своим
// проходом (см. applyLang ниже), а то, что нарисовано кодом, — своими руками.
const listeners = new Set();
export function onLang(fn) { listeners.add(fn); return () => listeners.delete(fn); }

// ---- разметка --------------------------------------------------------------

// Текст в index.html переводится проходом по узлам с пометкой data-t. Писать
// там t`…` нельзя — это не код, а разметка; зато пометка позволяет держать
// русский прямо в файле, как сейчас, и не плодить второй index.html.
//
//   <button data-t>панель GeoGebra</button>
//   <button data-t-title title="каким движком считать">Компланатор</button>
//
// Исходный русский запоминается при первом проходе: иначе второй перевод
// пошёл бы уже с английского и ключа бы не нашёл.
// ПРОБЕЛЫ В КЛЮЧЕ СХЛОПЫВАЮТСЯ.
//
// Абзац в разметке переносится и отступается как удобно читать, и если брать
// его дословно, ключ окажется зависим от отступа: переформатировали файл —
// перевод отвалился молча. Для показа это ничего не меняет, html всё равно
// схлопывает пробелы сам.
const flat = s => s.trim().replace(/\s+/g, ' ');

export function applyLang(root = document) {
  for (const node of root.querySelectorAll('[data-t]')) {
    if (!node.dataset.tRu) node.dataset.tRu = flat(node.textContent);
    node.textContent = t(node.dataset.tRu);
  }
  // ТЕКСТ С РАЗМЕТКОЙ ВНУТРИ — отдельной пометкой.
  //
  // В абзацах витрины есть <b> и <code>, и подмена textContent их схлопнула
  // бы. Здесь меняется innerHTML, а словарь хранит перевод вместе с теми же
  // тегами. Это безопасно ровно потому, что источник свой: словарь лежит в
  // репозитории, а не приходит от посетителя.
  for (const node of root.querySelectorAll('[data-t-html]')) {
    if (!node.dataset.tRuHtml) node.dataset.tRuHtml = flat(node.innerHTML);
    node.innerHTML = t(node.dataset.tRuHtml);
  }
  for (const node of root.querySelectorAll('[data-t-title]')) {
    if (!node.dataset.tRuTitle) node.dataset.tRuTitle = node.title;
    node.title = t(node.dataset.tRuTitle);
  }
}
