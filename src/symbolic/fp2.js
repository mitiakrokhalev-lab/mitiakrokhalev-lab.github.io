// Конечное поле F_p² = F_p[i], в котором живут гауссовы коэффициенты движка.
//
// Зачем поле: все дорогие места многомерного НОДа упираются не в число
// операций, а в РОСТ КОЭФФИЦИЕНТОВ. Последовательность псевдоостатков считает
// то, что надо, но по дороге числа раздуваются до тысяч знаков, и арифметика
// больших целых съедает всё время. В конечном поле числа не растут вовсе.
//
// Почему p ≡ 3 (mod 4): тогда −1 не квадрат по модулю p, значит x²+1 неприводим,
// значит F_p[x]/(x²+1) — поле, и пара (re, im) ведёт себя ровно как гауссово
// число. При p ≡ 1 (mod 4) это было бы кольцо с делителями нуля, и деление
// начало бы врать молча.
//
// **Элемент поля — ЧИСЛО, а не объект.** Пара (re, im) складывается в одно
// число как re·p + im. Это не микрооптимизация: первая версия заводила на
// каждый коэффициент объект с методами, и замер показал 446 микросекунд на узел
// рекурсии при входе в 29 членов — то есть пятнадцать микросекунд на член. Всё
// время уходило в аллокацию и сборку мусора, а не в арифметику. Распаковка
// стоит одного деления, и она несравнимо дешевле.
//
// Размер простого: вся арифметика идёт на точных целых double. Самое большое
// промежуточное значение — сумма двух произведений вычетов, то есть 2p², плюс
// упаковка требует p·p. Потолок 2^53 даёт p < 6.7·10^7; берём около 2^25, и
// упакованный элемент (< p²) заведомо остаётся точным.

export function isFieldPrime(p) {
  if (p < 2 || p % 4 !== 3) return false;
  for (let d = 2; d * d <= p; d++) if (p % d === 0) return false;
  return true;
}

// Простые выдаются ПО ТРЕБОВАНИЮ, а не берутся из готового списка.
//
// Раньше список был фиксированный, из двенадцати штук, и это была настоящая
// дыра: двенадцать простых дают модуль примерно в 300 бит, то есть коэффициенты
// НОДа примерно до 10^45. Ответ крупнее — и модулярный путь сдавался, а работу
// подхватывал старый, который на таких задачах молол часами. Причина отказа при
// этом была не математическая, а «в списке кончились числа».
//
// Теперь их столько, сколько нужно: ниже 2^25 простых вида 4k+3 около восьмисот
// тысяч, каждое даёт 25 бит модуля. Исчерпать этот запас нельзя — раньше
// кончится память под сам ответ.
//
// Проверка простоты — деление до корня (около 2900 шагов), и делается она один
// раз на простое: найденные копятся в списке.
const found = [];
let scan = 33554383;                 // ≡ 3 (mod 4), и 2p² ещё точное целое

export function primeAt(index) {
  while (found.length <= index) {
    while (!isFieldPrime(scan)) scan -= 4;      // шаг 4 сохраняет остаток 3
    found.push(scan);
    scan -= 4;
  }
  return found[index];
}

// Поле как замыкание по простому: p живёт в замыкании, а не в каждом элементе.
export function makeField(p) {
  const norm = x => ((x % p) + p) % p;

  function power(base, exp) {
    let r = 1, b = base % p;
    while (exp > 0) {
      if (exp & 1) r = (r * b) % p;
      b = (b * b) % p;
      exp >>= 1;
    }
    return r;
  }

  const re = c => (c / p) | 0;
  const im = c => c % p;
  const pack = (r, i) => r * p + i;

  const bigP = BigInt(p);

  return {
    p,
    zero: 0,
    one: p,                       // re = 1, im = 0
    re,
    im,
    of: (r, i = 0) => pack(norm(r), norm(i)),

    isZero: c => c === 0,
    isOne: c => c === p,

    add(x, y) {
      const r = re(x) + re(y), i = im(x) + im(y);
      return (r >= p ? r - p : r) * p + (i >= p ? i - p : i);
    },

    sub(x, y) {
      const r = re(x) - re(y), i = im(x) - im(y);
      return (r < 0 ? r + p : r) * p + (i < 0 ? i + p : i);
    },

    neg(x) {
      const r = re(x), i = im(x);
      return (r === 0 ? 0 : p - r) * p + (i === 0 ? 0 : p - i);
    },

    mul(x, y) {
      const xr = (x / p) | 0, xi = x % p;
      const yr = (y / p) | 0, yi = y % p;
      const r = (xr * yr - xi * yi) % p;
      return (r < 0 ? r + p : r) * p + (xr * yi + xi * yr) % p;
    },

    // Обратный: сопряжённое, делённое на норму. Норма ненулевого элемента нулю
    // не равна никогда — ровно потому, что p ≡ 3 (mod 4).
    inv(x) {
      const r = (x / p) | 0, i = x % p;
      const n = (r * r + i * i) % p;
      if (n === 0) throw new Error('деление на ноль в F_p²');
      const t = power(n, p - 2);
      return ((r * t) % p) * p + (i === 0 ? 0 : ((p - i) * t) % p);
    },

    div(x, y) { return this.mul(x, this.inv(y)); },

    // Дробь в поле; null, если знаменатель делится на p — тогда простое
    // «плохое» и брать надо следующее.
    ofFraction(f) {
      const d = Number(((f.d % bigP) + bigP) % bigP);
      if (d === 0) return null;
      const n = Number(((f.n % bigP) + bigP) % bigP);
      return (n * power(d, p - 2)) % p;
    },

    ofCFrac(c) {
      const r = this.ofFraction(c.re);
      const i = this.ofFraction(c.im);
      if (r === null || i === null) return null;
      return r * p + i;
    },

    // Гауссово целое {re, im} из bigint-ов.
    ofGz(z) {
      return Number(((z.re % bigP) + bigP) % bigP) * p
        + Number(((z.im % bigP) + bigP) % bigP);
    },
  };
}
