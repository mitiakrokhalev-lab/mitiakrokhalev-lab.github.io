// Бюджет на счёт.
//
// Живёт отдельным модулем не из любви к порядку, а по необходимости: проверять
// бюджет надо и в самом низу (умножение многочленов), и в самом верху (мост), а
// низ ни от чего зависеть не должен. Через gcd.js это дало бы кольцевой импорт.
//
// Зачем вообще. У разложения на множители бюджет был всегда: оно украшение, и
// сдаться там ничего не стоит. Со СЧЁТОМ так нельзя — несокращённая дробь
// становится входом следующей операции, и рост идёт с умножением. Поэтому здесь
// бюджет означает не «посчитай похуже», а «остановись и скажи».
//
// Урок, оплаченный дважды. Сначала проверка стояла только на входе в НОД — и
// объект считался 121 секунду, а «не посчитано за 5 с» появлялось в самом конце:
// между вызовами НОДа лежат умножения и деления многочленов, и одного такого
// умножения на больших выражениях хватает на минуту. Проверка обязана стоять
// ВЕЗДЕ, где может пройти много времени, а не только там, где его обычно много.
export class BudgetExceeded extends Error {
  constructor(ms, peak) {
    super(`счёт не уложился в ${(ms / 1000).toFixed(0)} с`);
    this.name = 'BudgetExceeded';
    this.budgetMs = ms;
    this.peak = peak;
  }
}

let deadline = Infinity;
let budget = 0;
let peak = 0;

// Запускает fn с ограничением по времени. Вложенные вызовы бюджет не
// переоткрывают: он общий на весь объект, иначе каждая из полудюжины операций
// внутри честно получила бы свой полный бюджет.
export function withComputeBudget(ms, fn) {
  if (deadline !== Infinity) return fn();
  deadline = ms === Infinity ? Infinity : Date.now() + ms;
  budget = ms;
  peak = 0;
  try { return fn(); } finally { deadline = Infinity; }
}

// Размер самого большого промежуточного многочлена — по нему потом оценивается,
// сколько ждать полного счёта.
export function noteSize(n) { if (n > peak) peak = n; }
export function lastPeak() { return peak; }

// Короткий срок ВНУТРИ общего бюджета.
//
// Нужен для перебора вариантов: стоимость некоторых алгоритмов дико зависит от
// сделанного выбора (по какой переменной вести последовательность
// псевдоостатков), а предсказать хороший выбор заранее нельзя. Зато можно дать
// каждому маленький срок и, если не уложился, взять следующий.
//
// Отличать от исчерпания общего бюджета обязательно: срок означает «попробуй
// иначе», а бюджет — «остановись и скажи пользователю».
export class SliceExceeded extends Error {
  constructor() { super('срок попытки истёк'); this.name = 'SliceExceeded'; }
}

let sliceDeadline = Infinity;

export function withSlice(ms, fn) {
  const previous = sliceDeadline;
  const own = Date.now() + ms;
  sliceDeadline = own < previous ? own : previous;
  try { return fn(); } finally { sliceDeadline = previous; }
}

export function checkComputeBudget() {
  const now = Date.now();
  // Общий бюджет проверяется ПЕРВЫМ: он главнее, и его истечение не должно
  // выглядеть как «попробуй другой вариант».
  if (deadline !== Infinity && now > deadline) throw new BudgetExceeded(budget, peak);
  if (sliceDeadline !== Infinity && now > sliceDeadline) throw new SliceExceeded();
}

// Проверка для горячих мест, где Date.now() на каждый вызов был бы заметен сам
// по себе.
//
// Порог по размеру ОДНОЙ операции тут не годится, и это выяснилось дорого:
// миллион мелких сложений — каждое «лёгкое», ни одно порога не достигает, а
// вместе они идут минуты, и бюджет молчит. Поэтому копим работу и спрашиваем
// часы, когда накопилось достаточно: расход на Date.now() размазывается, а
// пропустить длинный счёт становится нельзя.
const WORK_SLICE = 200_000;
let work = 0;

export function checkIfHeavy(amount) {
  work += amount;
  if (work < WORK_SLICE) return;
  work = 0;
  checkComputeBudget();
}
