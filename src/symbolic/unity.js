import { QuadraticExt, baseRingOf } from './quadratic-ext.js';

// Мнимая единица в синтаксисе GeoGebra (U+03AF, не латинская i: та занята под
// имена). Продублирована здесь намеренно: слой symbolic не должен зависеть от
// слоя geogebra, иначе получается импорт по кругу, которого сборщик не умеет.
const IMAGINARY_UNIT = 'ί';

// Первообразные корни из единицы: ζ_n = e^{2πi/n}.
//
// Зачем. Движок считает в Q(i)(a,b,c), и поворот на угол α — это умножение на
// e^{iα}. В базовом поле лежат ровно четыре таких числа: 1, i, −1, −i, поэтому
// до сих пор поддерживались только повороты, кратные 90°. Все остальные
// «понятные» углы — 60°, 45°, 36°, 30° — требуют присоединить корень.
//
// Ключевое наблюдение, которое делает это дёшево: механизм присоединения у нас
// уже есть, и он КВАДРАТИЧНЫЙ, а нужен ровно он. Степень Q(ζ_n) над Q равна
// φ(n), и это степень двойки в точности тогда, когда правильный n-угольник
// строится циркулем и линейкой (теорема Гаусса–Ванцеля). То есть «понятные
// углы» и «то, что укладывается в башню квадратичных расширений» — это одно и
// то же множество, и никакого нового механизма не требуется.
//
// Важно: базовое поле УЖЕ содержит i, поэтому этажей нужно меньше, чем можно
// подумать. Q(i, ζ₃) = Q(ζ₁₂), и это всего один этаж — а даёт сразу все
// повороты, кратные 30°.
//
// И ещё одно, неочевидное: глубина башни здесь стоит почти НИЧЕГО, хотя для
// геометрических корней третий этаж неподъёмен. Причина в том, что потолок там
// упирается в размер выражений: уравнение очередного этажа живёт в предыдущем и
// растёт вместе с ним. А у корня из единицы коэффициенты — ЧИСЛА, никаких a, b,
// c в них нет, и расти нечему. Замерено: ζ₃₂ (пять этажей) строится за 24 мс,
// ζ₆₀ — за 124 мс, и порядок у каждого проверен алгебраически.
//
// Что получается (всё замерено, порядок проверен возведением в степень):
//
//   | n                      | углы                | время |
//   |------------------------|---------------------|-------|
//   | 1, 2, 4                | 180°, 90°           | 0     |
//   | 3, 6, 12               | 120°, 60°, 30°      | <1 мс |
//   | 8, 16, 32              | 45°, 22.5°, 11.25°  | ~20 мс|
//   | 5, 10, 20, 40          | 72°, 36°, 18°, 9°   | ~60 мс|
//   | 15, 24, 30, 48, 60     | 24°, 15°, 12°, 6°   | ~100 мс|
//   | 7, 9, 11, 13, 14, …    | не строится вовсе   | отказ |
//   | 17, 257, 65537         | строится, но нужны периоды Гаусса | отказ |

const FERMAT_PRIMES = [3, 5, 17, 257, 65537];

// Разложение на простые — числа тут крошечные, поэтому перебор делителей.
function factorize(n) {
  const out = new Map();
  let m = n;
  for (let p = 2; p * p <= m; p++) {
    while (m % p === 0) { out.set(p, (out.get(p) ?? 0) + 1); m /= p; }
  }
  if (m > 1) out.set(m, (out.get(m) ?? 0) + 1);
  return out;
}

// Строится ли правильный n-угольник: n = 2^k, умноженное на попарно различные
// простые Ферма. Это ровно условие Гаусса–Ванцеля.
export function isConstructible(n) {
  if (!Number.isInteger(n) || n < 1) return false;
  for (const [p, a] of factorize(n)) {
    if (p === 2) continue;
    if (a > 1) return false;                    // p² с нечётным p уже не то
    if (!FERMAT_PRIMES.includes(p)) return false;
  }
  return true;
}

// s·a + t·b = НОД(a, b) — расширенный Евклид. Нужен для склейки взаимно
// простых частей: 1/(ab) = s/b + t/a, откуда ζ_{ab} = ζ_b^s · ζ_a^t.
function bezout(a, b) {
  let [oldR, r] = [a, b];
  let [oldS, s] = [1, 0];
  let [oldT, t] = [0, 1];
  while (r !== 0) {
    const q = Math.floor(oldR / r);
    [oldR, r] = [r, oldR - q * r];
    [oldS, s] = [s, oldS - q * s];
    [oldT, t] = [t, oldT - q * t];
  }
  return { g: oldR, s: oldS, t: oldT };
}

function power(value, e) {
  if (e === 0) return value.ring.one();
  const base = e < 0 ? value.inv() : value;
  let acc = base;
  for (let k = 1; k < Math.abs(e); k++) acc = acc.mul(base);
  return acc;
}

// Числовое значение корня и его определение для GeoGebra.
//
// Здесь корень из единицы устроен ЛУЧШЕ, чем геометрический: у того численное
// значение приходится брать с чертежа (см. evalFloat в quadratic-ext.js), а
// тут оно известно точно и заранее. Поэтому точка, построенная через ζ_n,
// рисуется сразу, без вспомогательной секущей и без вопроса «который из двух
// корней наш».
function pin(ext, n) {
  const angle = 2 * Math.PI / n;
  ext.numericRoot = { re: Math.cos(angle), im: Math.sin(angle) };
  ext.ggbRoot = `(cos(2*pi/${n})+${IMAGINARY_UNIT}*sin(2*pi/${n}))`;
  return ext;
}

// Присоединение корня уравнения z² − Sz + Q = 0, лежащего на единичной
// окружности, в двух видах.
//
// (A) Q = 1: тогда второй корень — это 1/ζ, то есть само комплексное
//     сопряжение. Значит conj(ζ) = S − ζ, и правило сопряжения бесплатно.
// (B) z² = w: второй корень −ζ сопряжением НЕ является, зато 1/ζ = ζ/w,
//     потому что ζ² = w. Отсюда conj(ζ) = ζ·w⁻¹.
function adjoinReciprocal(base, S, n, name) {
  const ext = new QuadraticExt(base, S, base.one(), name);
  ext.conjRoot = ext.lift(S).sub(ext.root());
  return pin(ext, n);
}

function adjoinSquareRootOf(base, w, n, name) {
  const ext = new QuadraticExt(base, base.zero(), w.neg(), name);
  ext.conjRoot = ext.root().mul(ext.lift(w.inv()));
  return pin(ext, n);
}

// ζ_{2^k}. До четвёртой степени всё уже есть в базовом поле — там живёт i.
// Дальше каждый следующий этаж это «извлечь корень из предыдущего»: ζ_16² = ζ_8.
function powerOfTwoRoot(base, N) {
  if (N === 1) return base.one();
  if (N === 2) return base.one().neg();
  if (N === 4) return base.i();
  // Основанием служит то поле, где ЛЕЖИТ предыдущий корень, а не базовое:
  // начиная с ζ₁₆ он сам уже иррационален, и уравнение z² = ζ₈ живёт этажом
  // выше. С базовым кольцом здесь получалось расширение, чей свободный член
  // ему не принадлежит, — и первое же умножение упиралось в «значения из
  // разных расширений».
  const half = powerOfTwoRoot(base, N / 2);
  return adjoinSquareRootOf(half.ring, half, N, `ζ${N}`).root();
}

// ζ_p для нечётного простого p. Минимальный многочлен ζ_p над Q имеет степень
// p−1, но нам нужен не он: ζ_p удовлетворяет КВАДРАТНОМУ уравнению
// z² − Sz + 1 = 0 с S = ζ_p + ζ_p⁻¹ = 2cos(2π/p). Вся работа — построить S,
// а это уже вещественное число из башни.
function oddPrimeRoot(base, p) {
  if (p === 3) {
    // 2cos120° = −1, поэтому z² + z + 1 — и это ровно один этаж.
    return adjoinReciprocal(base, base.one().neg(), 3, 'ω').root();
  }
  if (p === 5) {
    // 2cos72° = (√5 − 1)/2. Сначала √5 — обычный вещественный радикал, его
    // сопряжение равно ему самому; потом уже сам корень из единицы.
    const sqrt5 = new QuadraticExt(base, base.zero(), base.constant(-5n), '√5');
    sqrt5.conjRoot = sqrt5.root();
    sqrt5.numericRoot = { re: Math.sqrt(5), im: 0 };
    sqrt5.ggbRoot = 'sqrt(5)';
    const S = sqrt5.root().sub(sqrt5.one()).div(2n);
    return adjoinReciprocal(sqrt5, S, 5, 'ζ5').root();
  }
  // Для остальных простых Ферма (17, 257, 65537) угольник СТРОИТСЯ, и башня
  // его бы выдержала — глубина здесь дёшева. Не хватает другого: значения
  // S = 2cos(2π/p) для них выражаются через периоды Гаусса, а это отдельная
  // конструкция, которой в движке нет. Отказ честный: не «нельзя», а «не
  // сделано», и 3 с 5 закрывают все углы, которые кто-либо чертит.
  throw new Error(`корень степени ${p} из единицы: правильный ${p}-угольник строится циркулем `
    + `и линейкой, но для этого нужны периоды Гаусса — в движке их нет. `
    + `Из нечётных поддержаны 3 и 5 (и любые их произведения со степенями двойки)`);
}

function oddRoot(base, m) {
  if (m === 1) return base.one();
  const factors = [...factorize(m)];
  if (factors.length === 1) {
    const [p, a] = factors[0];
    if (a > 1) {
      throw new Error(`корень степени ${m} из единицы не выражается в квадратичных `
        + `радикалах: правильный ${m}-угольник не строится циркулем и линейкой`);
    }
    return oddPrimeRoot(base, p);
  }
  // Взаимно простые части склеиваются по китайской теореме об остатках:
  // 1/(ab) = s/b + t/a, значит ζ_{ab} = ζ_b^s · ζ_a^t.
  const [p, a] = factors[0];
  const A = p ** a;
  const B = m / A;
  const { s, t } = bezout(B, A);
  return power(oddRoot(base, A), s).mul(power(oddRoot(base, B), t));
}

// ζ_n целиком. Чётную и нечётную части строим порознь и склеиваем тем же
// китайским остатком — они взаимно просты по построению.
function build(base, n) {
  if (!isConstructible(n)) {
    throw new Error(`корень степени ${n} из единицы не выражается в квадратичных `
      + `радикалах: правильный ${n}-угольник не строится циркулем и линейкой`);
  }
  let k = 0;
  let m = n;
  while (m % 2 === 0) { m /= 2; k++; }
  const A = 2 ** k;
  if (m === 1) return powerOfTwoRoot(base, A);
  if (A === 1) return oddRoot(base, m);
  const { s, t } = bezout(m, A);
  return power(powerOfTwoRoot(base, A), s).mul(power(oddRoot(base, m), t));
}

// Первообразный корень степени n из единицы в кольце `ring`.
//
// Кэш обязателен, а не желателен: два вызова обязаны вернуть значение ОДНОГО
// поля, иначе движок заведёт два одинаковых по смыслу расширения, и величины
// из них никогда не сравнятся. Кэш висит на базовом кольце — оно и есть
// построение.
export function rootOfUnity(ring, n) {
  if (!Number.isInteger(n) || n < 1) {
    throw new Error(`unity: степень корня должна быть целым положительным числом, а не «${n}»`);
  }
  const base = baseRingOf(ring);
  const cache = (base.unityCache ??= new Map());
  if (!cache.has(n)) cache.set(n, build(base, n));
  return cache.get(n);
}
