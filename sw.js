// Установка приложения (PWA) убрана: лишняя сущность, которая сама просилась
// установиться и путала — особенно теперь, когда часть движков платная и
// «приложение» выглядело отдельным продуктом.
//
// НО ПРОСТО УДАЛИТЬ ЭТОТ ФАЙЛ НЕЛЬЗЯ, И ЭТО НЕ ОСТОРОЖНОСТЬ, А НЕОБХОДИМОСТЬ.
//
// У всех, кто заходил раньше, прежний работник ОСТАЁТСЯ ЗАРЕГИСТРИРОВАННЫМ в
// браузере. Он переживает и перезагрузку, и обновление сайта: страница
// собирается из его кэша, а не из сети. Убрать регистрацию со страницы
// недостаточно — она снимает только НОВЫЕ установки, а старые продолжают
// работать и отдавать прошлогоднюю версию приложения. Удаление файла делает
// ещё хуже: работник остаётся, а обновиться ему неоткуда.
//
// Единственный способ отменить работника — прислать браузеру нового, который
// снимет себя сам. Браузер перепроверяет этот адрес при каждой загрузке
// страницы, поэтому замена доезжает до всех.
//
// ЭТОТ ФАЙЛ ДОЛЖЕН ЛЕЖАТЬ ЗДЕСЬ ЕЩЁ ДОЛГО — пока не вернётся последний, кто
// успел установить приложение. Год как минимум. Удалять его просто потому,
// что «он ничего не делает», нельзя: он именно этим и занят.

self.addEventListener('install', () => {
  // Не ждать, пока закроются вкладки со старым работником.
  self.skipWaiting();
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    // Кэши прежнего работника — в них лежит старая версия приложения.
    for (const name of await caches.keys()) await caches.delete(name);
    await self.registration.unregister();
    // Перезагружаем открытые вкладки: без этого они до самого закрытия
    // продолжают ходить через уже снятого работника.
    for (const client of await self.clients.matchAll({ type: 'window' })) {
      client.navigate(client.url).catch(() => { /* вкладку могли закрыть */ });
    }
  })());
});

